// Convert a JRXML style to CSS style
function convertStyleToCSS(style: any) {
    if (!style) return {};

    const styles: any = {};

    // Text style
    if (style.fontSize) {
        styles.fontSize = `${style.fontSize}px`;
    }
    if (style.forecolor) {
        styles.color = style.forecolor;
    }
    if (style.isBold) {
        styles.fontWeight = "bold";
    }
    if (style.isItalic) {
        styles.fontStyle = "italic";
    }
    if (style.isUnderline) {
        styles.textDecoration = "underline";
    }
    if (style.mode === "Opaque" && style.backcolor) {
        styles.backgroundColor = style.backcolor;
    }

    // Text alignment
    if (style.textAlignment) {
        const align = style.textAlignment.toLowerCase();
        switch (align) {
            case "left":
                styles.justifyContent = "flex-start";
                break;
            case "center":
                styles.justifyContent = "center";
                break;
            case "right":
                styles.justifyContent = "flex-end";
                break;
            case "justified":
                styles.justifyContent = "space-between";
                break;
            default:
                styles.justifyContent = "center";
        }
    }
    // Vertical alignment
    if (style.verticalAlignment) {
        const align = style.verticalAlignment.toLowerCase();
        switch (align) {
            case "top":
                styles.alignItems = "flex-start";
                break;
            case "middle":
                styles.alignItems = "center";
                break;
            case "bottom":
                styles.alignItems = "flex-end";
                break;
            default:
                styles.alignItems = "center";
        }
    }

    // Border style
    let borderWidth = 0;
    let borderStyle = "solid";
    let borderColor = "#000000";

    if (style.box && style.box.pen) {
        borderWidth = style.box.pen.lineWidth || 0;
        borderStyle = style.box.pen.lineStyle || "solid";
        borderColor = style.box.pen.lineColor || "#000000";
    }

    if (borderWidth > 0) {
        styles.border = `${borderWidth}px ${borderStyle} ${borderColor}`;
    }

    return styles;
}

// Get the cell style
function getCellStyle(cell: any, cellType?: string) {
    if (!cell) return {};

    const styles: any = {};

    // First get the style from tableStyles based on cellType
    if (cellType && props.tableStyles) {
        let styleName = "";
        switch (cellType) {
            case "tableHeader":
                styleName = props.tableStyles.tableHeader;
                break;
            case "columnHeader":
                styleName = props.tableStyles.columnHeader;
                break;
            case "columnFooter":
                styleName = props.tableStyles.columnFooter;
                break;
            case "detailCell":
                styleName = props.tableStyles.detailCell;
                break;
        }

        if (styleName) {
            const style = getStyleByName(styleName);
            if (style) {
                Object.assign(styles, convertStyleToCSS(style));
            }
        }
    }

    // Then check whether cell has a style property, overriding the style from tableStyles
    if (cell.style) {
        const style = getStyleByName(cell.style);
        if (style) {
            Object.assign(styles, convertStyleToCSS(style));
        }
    }

    // Then apply the cell's own style, overriding the style from `style`
    // Text style
    if (cell.fontSize) {
        styles.fontSize = `${cell.fontSize}px`;
    } else {
        // Default font size 10, consistent with JasperReport Studio
        styles.fontSize = "10px";
    }
    if (cell.forecolor) {
        styles.color = cell.forecolor;
    }
    if (cell.isBold) {
        styles.fontWeight = "bold";
    } else {
        styles.fontWeight = "normal";
    }
    if (cell.isItalic) {
        styles.fontStyle = "italic";
    }
    if (cell.isUnderline) {
        styles.textDecoration = "underline";
    }
    if (cell.mode === "Opaque" && cell.backcolor) {
        styles.backgroundColor = cell.backcolor;
    }

    // Text alignment - since cell-content uses flex layout, justify-content needs to be set
    if (cell.textAlignment) {
        const align = cell.textAlignment.toLowerCase();
        switch (align) {
            case "left":
                styles.justifyContent = "flex-start";
                break;
            case "center":
                styles.justifyContent = "center";
                break;
            case "right":
                styles.justifyContent = "flex-end";
                break;
            case "justified":
                styles.justifyContent = "space-between";
                break;
            default:
                styles.justifyContent = "center";
        }
    }
    // Vertical alignment - since cell-content uses flex layout, align-items needs to be set
    if (cell.verticalAlignment) {
        const align = cell.verticalAlignment.toLowerCase();
        switch (align) {
            case "top":
                styles.alignItems = "flex-start";
                break;
            case "middle":
                styles.alignItems = "center";
                break;
            case "bottom":
                styles.alignItems = "flex-end";
                break;
            default:
                styles.alignItems = "center";
        }
    }

    // Finally apply cell.element's style, overriding the style from cell, to ensure the element's own style has the highest priority
    if (cell.element) {
        // Text style
        if (cell.element.fontSize) {
            styles.fontSize = `${cell.element.fontSize}px`;
        }
        if (cell.element.forecolor) {
            styles.color = cell.element.forecolor;
        }
        if (cell.element.isBold) {
            styles.fontWeight = "bold";
        } else {
            styles.fontWeight = "normal";
        }
        if (cell.element.isItalic) {
            styles.fontStyle = "italic";
        }
        if (cell.element.isUnderline) {
            styles.textDecoration = "underline";
        }
        if (cell.element.mode === "Opaque" && cell.element.backcolor) {
            styles.backgroundColor = cell.element.backcolor;
        }

        // Text alignment
        if (cell.element.textAlignment) {
            const align = cell.element.textAlignment.toLowerCase();
            switch (align) {
                case "left":
                    styles.justifyContent = "flex-start";
                    break;
                case "center":
                    styles.justifyContent = "center";
                    break;
                case "right":
                    styles.justifyContent = "flex-end";
                    break;
                case "justified":
                    styles.justifyContent = "space-between";
                    break;
                default:
                    styles.justifyContent = "center";
            }
        }
        // Vertical alignment
        if (cell.element.verticalAlignment) {
            const align = cell.element.verticalAlignment.toLowerCase();
            switch (align) {
                case "top":
                    styles.alignItems = "flex-start";
                    break;
                case "middle":
                    styles.alignItems = "center";
                    break;
                case "bottom":
                    styles.alignItems = "flex-end";
                    break;
                default:
                    styles.alignItems = "center";
            }
        }
    }

    return styles;
}

