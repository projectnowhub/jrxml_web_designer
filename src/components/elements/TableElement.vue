// Handle column click event, supporting multi-select
function handleColumnClick(index: number, event: MouseEvent) {
    const isMultiSelect = event.ctrlKey || event.shiftKey || event.metaKey;

    if (isMultiSelect) {
        // Multi-select mode: toggle the column's selected state
        if (selectedColumns.value.includes(index)) {
            // Deselect
            selectedColumns.value = selectedColumns.value.filter(
                (colIndex) => colIndex !== index,
            );
        } else {
            // Add to selection
            selectedColumns.value.push(index);
            // Keep the selected indices sorted
            selectedColumns.value.sort((a, b) => a - b);
        }
        // In multi-select mode, stop event propagation to preserve the column selection state
        event.stopPropagation();
    } else {
        // Single-select mode: select only the current column
        selectedColumns.value = [index];
        // In single-select mode, allow the event to bubble up, triggering table element selection
        // event.stopPropagation(); // Removed stopPropagation to let BaseElement handle selection
        // Directly emit the table element's select event
        emit(
            "select",
            props.bandIndex,
            props.elementIndex,
            false,
            props.parentFrameIndex,
        );
    }
}

